import { API_BASE_URL, authorizedFetch } from '../store/apiSlice.js'

async function fetchBlob(url) {
  const response = await authorizedFetch(url)

  if (!response.ok) {
    let message = `Export failed (status ${response.status}).`
    try {
      const body = await response.json()
      message = body?.message || body?.error?.message || message
    } catch {
      // response file thi ya HTML error page, JSON nahi tha - default message hi rakho
    }
    throw new Error(message)
  }

  return response.blob()
}

function triggerDownload(blob, filename) {
  const url = window.URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = filename
  document.body.appendChild(link)
  link.click()
  link.remove()
  window.URL.revokeObjectURL(url)
}

// GET {{server_url}}/admin/reports/export?from_date=YYYY-MM-DD&to_date=YYYY-MM-DD
// Poori company ka multi-sheet Excel workbook (Monthly Summary / Daily Attendance / Late Report / Leave Report)
// This workbook is generated by the backend, so its language remains a backend concern (a future `lang` query parameter could address it).
export async function downloadCompanyExcelReport({ fromDate, toDate }) {
  const url = `${API_BASE_URL}/admin/reports/export?from_date=${encodeURIComponent(fromDate)}&to_date=${encodeURIComponent(toDate)}`
  const blob = await fetchBlob(url)
  triggerDownload(blob, `attendance-report-${fromDate}_to_${toDate}.xlsx`)
}

// Client-side generated Excel — sirf ek employee ka poora data (summary + daily/late/leave),
// already-fetched normalized data se banta hai, koi extra API call nahi lagti.
// Isko chalane ke liye "xlsx" (SheetJS) package chahiye: npm install xlsx
export async function downloadEmployeeExcelReport({ employee, fromDate, toDate, summary, dailyRows = [], lateRows = [], leaveRows = [], t, formatters }) {
  const XLSX = await import('xlsx')
  const rangeLabel = `${fromDate}_to_${toDate}`
  const label = (key) => t(`excel.columns.${key}`)

  const summarySheet = XLSX.utils.json_to_sheet([
    {
      [label('employeeCode')]: employee.code, [label('name')]: employee.name, [label('department')]: employee.department || '',
      [label('workingDays')]: summary?.workingDays ?? '', [label('presentDays')]: summary?.presentDays ?? '', [label('absentDays')]: summary?.absentDays ?? '', [label('leaveDays')]: summary?.leaveDays ?? '', [label('holidayDays')]: summary?.holidayDays ?? '', [label('lateCount')]: summary?.lateCount ?? '', [label('totalLate')]: summary?.totalLateMinutes ?? '', [label('workedHours')]: summary?.workedHours ?? ''
    }
  ])

  const lateSheet = XLSX.utils.json_to_sheet(
    lateRows.length
      ? lateRows.map((row) => ({
          [label('date')]: row.date, [label('expectedIn')]: row.expectedLogin, [label('actualIn')]: row.checkIn ? formatters.dateTime(row.checkIn) : '', [label('lateMin')]: row.lateMinutes
        }))
      : [{ [label('date')]: '', [label('expectedIn')]: '', [label('actualIn')]: '', [label('lateMin')]: '' }]
  )

  const leaveSheet = XLSX.utils.json_to_sheet(
    leaveRows.length
      ? leaveRows.map((row) => ({
          [label('type')]: row.leaveTypeName, [label('start')]: row.startDate, [label('end')]: row.endDate, Duration: row.durationType, [label('days')]: row.totalDays, [label('status')]: row.status, [label('reason')]: row.reason
        }))
      : [{ [label('type')]: '', [label('start')]: '', [label('end')]: '', Duration: '', [label('days')]: '', [label('status')]: '', [label('reason')]: '' }]
  )

  const workbook = XLSX.utils.book_new()
  XLSX.utils.book_append_sheet(workbook, summarySheet, t('excel.sheets.summary'))

  if (dailyRows.length) {
    const dailySheet = XLSX.utils.json_to_sheet(
      dailyRows.map((row) => ({
        [label('date')]: row.date, [label('status')]: row.status, [label('checkIn')]: row.checkIn ? formatters.time(row.checkIn) : '', [label('checkOut')]: row.checkOut ? formatters.time(row.checkOut) : '', [label('lateMin')]: row.lateMinutes, 'Early Min': row.earlyMinutes, 'Worked Min': row.workedMinutes
      }))
    )
    XLSX.utils.book_append_sheet(workbook, dailySheet, t('excel.sheets.daily'))
  }

  XLSX.utils.book_append_sheet(workbook, lateSheet, t('excel.sheets.late'))
  XLSX.utils.book_append_sheet(workbook, leaveSheet, t('excel.sheets.leave'))

  XLSX.writeFile(workbook, `${employee.code}-report-${rangeLabel}.xlsx`)
}